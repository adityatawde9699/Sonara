//! The on-disk layout of Sonara's local data (data version 2).
//!
//! ```text
//! <app_local_data>/
//!   data-version            "2"
//!   library.json
//!   progress/<sha>.json
//!   audio-cache/            content-addressed synthesis cache
//!   sessions/<run-id>/      one directory per synthesis run
//!   current-session         the run id of the session to reopen
//! ```
//!
//! Each run writes only inside its own directory, so a cancelled or failed
//! run can be deleted whole and never disturbs the session being listened to.

use std::fs;
use std::path::{Path, PathBuf};

use crate::session::{load_saved_session, ReaderSession};

pub(crate) const DATA_VERSION_FILE: &str = "data-version";
pub(crate) const DATA_VERSION: u32 = 2;
pub(crate) const SESSIONS_DIR: &str = "sessions";
pub(crate) const AUDIO_CACHE_DIR: &str = "audio-cache";
const CURRENT_SESSION_FILE: &str = "current-session";

pub(crate) fn sessions_dir(app_data: &Path) -> PathBuf {
    app_data.join(SESSIONS_DIR)
}

pub(crate) fn audio_cache_dir(app_data: &Path) -> PathBuf {
    app_data.join(AUDIO_CACHE_DIR)
}

/// Run ids are generated by Sonara (`make_job_id`, or `migrated-v1`); a
/// pointer naming anything else is ignored.
pub(crate) fn valid_run_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-')
}

/// Create an empty directory for a new run.
pub(crate) fn create_run_dir(app_data: &Path, run_id: &str) -> Result<PathBuf, String> {
    if !valid_run_id(run_id) {
        return Err("Could not name the new audio directory.".to_owned());
    }
    let dir = sessions_dir(app_data).join(run_id);
    fs::create_dir_all(sessions_dir(app_data))
        .and_then(|()| fs::create_dir(&dir))
        .map_err(|error| format!("Could not create Sonara's local audio directory: {error}"))?;
    Ok(dir)
}

/// Record which run is the current session. Written atomically.
pub(crate) fn set_current_session(app_data: &Path, run_dir: &Path) -> Result<(), String> {
    let run_id = run_dir
        .file_name()
        .and_then(|name| name.to_str())
        .filter(|name| valid_run_id(name))
        .ok_or_else(|| "The session directory has an unexpected name.".to_owned())?;
    let path = app_data.join(CURRENT_SESSION_FILE);
    let temp = app_data.join(format!(".{CURRENT_SESSION_FILE}.tmp"));
    fs::write(&temp, run_id)
        .and_then(|()| fs::rename(&temp, &path))
        .map_err(|error| {
            let _ = fs::remove_file(&temp);
            format!("Could not record the current session: {error}")
        })
}

/// The session named by `current-session`, if it still loads.
pub(crate) fn load_current_session(app_data: &Path) -> Option<ReaderSession> {
    let run_id = fs::read_to_string(app_data.join(CURRENT_SESSION_FILE)).ok()?;
    let run_id = run_id.trim();
    if !valid_run_id(run_id) {
        return None;
    }
    load_saved_session(&sessions_dir(app_data).join(run_id))
}

/// Delete every run directory except those in `keep`. Run at startup and
/// after a run finishes, so leftovers of crashed or cancelled runs go too.
pub(crate) fn prune_runs(app_data: &Path, keep: &[&Path]) {
    let Ok(entries) = fs::read_dir(sessions_dir(app_data)) else {
        return;
    };
    let keep: Vec<PathBuf> = keep
        .iter()
        .filter_map(|path| path.canonicalize().ok())
        .collect();
    for entry in entries.flatten() {
        let path = entry.path();
        // Only directories Sonara named; never follow a symlink out.
        let is_run_dir = entry.file_type().is_ok_and(|kind| kind.is_dir())
            && entry.file_name().to_str().is_some_and(valid_run_id);
        if !is_run_dir {
            continue;
        }
        let canonical = path.canonicalize().unwrap_or_else(|_| path.clone());
        if !keep.contains(&canonical) {
            let _ = fs::remove_dir_all(&path);
        }
    }
}

/// Remove one run directory, as after a cancelled or failed run.
pub(crate) fn remove_run(run_dir: &Path) {
    let _ = fs::remove_dir_all(run_dir);
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::make_job_id;

    #[test]
    fn pruning_keeps_only_named_runs_and_ignores_foreign_entries() {
        let root = std::env::temp_dir().join(format!("sonara-storage-{}", make_job_id()));
        let keep = create_run_dir(&root, "run-1").unwrap();
        let stale = create_run_dir(&root, "run-2").unwrap();
        fs::write(stale.join("audio_chunks.json"), b"{}").unwrap();
        let foreign_file = sessions_dir(&root).join("notes.txt");
        fs::write(&foreign_file, b"x").unwrap();
        let odd_dir = sessions_dir(&root).join("has space");
        fs::create_dir(&odd_dir).unwrap();

        prune_runs(&root, &[&keep]);
        assert!(keep.is_dir());
        assert!(!stale.exists());
        assert!(foreign_file.exists());
        assert!(odd_dir.exists());
        assert!(create_run_dir(&root, "run-1").is_err());
        assert!(create_run_dir(&root, "../escape").is_err());
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn the_current_session_pointer_is_validated() {
        let root = std::env::temp_dir().join(format!("sonara-pointer-{}", make_job_id()));
        let run = create_run_dir(&root, "run-1").unwrap();
        set_current_session(&root, &run).unwrap();
        assert_eq!(
            fs::read_to_string(root.join(CURRENT_SESSION_FILE)).unwrap(),
            "run-1"
        );
        // No session.json in the run yet, so there is nothing to reopen.
        assert!(load_current_session(&root).is_none());
        fs::write(root.join(CURRENT_SESSION_FILE), "../../etc").unwrap();
        assert!(load_current_session(&root).is_none());
        let _ = fs::remove_dir_all(&root);
    }
}
